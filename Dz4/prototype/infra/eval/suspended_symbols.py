"""Снятые сущности схемы в одном месте: список читают и гейт приёмки, и сторож документов.

Почему один модуль, а не два списка. ADR-048 п.1: правило и список обязаны читать одно
значение, иначе проверка становится фиктивной. Тот же довод, что и для `SUSPENDED_SYMBOLS`
в `review_gate.py`, переносится на живые документы: свой список снятого в тесте через год
проверяет не то, что сняли, а то, что автор теста перечислил.

**Правила у потребителей разные, и это не украшение.**

* Эталон набора (`review_gate.py`): там снятая сущность почти всегда ложное утверждение,
  поэтому правила регистрозависимы, а нода `Source` ищется по связке с `Chunk`/`anchor` —
  в домене `cinema` есть документ, буквально названный «Source».
* Живой документ (`tests/test_docs_consistency.py`): там одно и то же слово бывает и снятой
  сущностью, и честной историей — «ADR-046 п. 9 снял `CONTAINS`». Поэтому правило другое и
  заяглённое: ловится **абзац, который называет снятую сущность, не сказав в этом же абзаце,
  что она снята**.

Граница «абзац, а не строка» выбрана потому, что истории про снятое занимают три-четыре строки
(`docs/06_operations_and_risks.md` §2.6 — четыре). Построчная проверка либо заставила бы
историю замолчать, либо научила бы обходить себя: достаточно дописать пометку в соседней
строке абзаца.

**Измеренная цена этого решения, а не только описанная.** Проверка на HEAD-копиях шести
документов, где правки ещё не внесены: абзацный маркер ловит **9** живых лжей из 11 и пропускает
две — `docs/operations_requirements.md` (маркер «не существует» стоит про Параметры «N версий»,
то есть про другое) и `docs/adapters_specification.md:281` (одна строка честно упоминает
`CONTAINS` как «раньше» и тут же утверждает, что `Source` сохраняется). Обе пропущены по одной
причине: **маркер в соседней фразе прощает весь абзац**. Узкая альтернатива — маркер в
предложении — проверена и отклонена по измерению: она ловит 11 из 11, но даёт **2 ложных
срабатывания на правильном тексте** (`docs/06_operations_and_risks.md` §2.6 и docstring в блоке
интерфейса `docs/adapters_specification.md`), то есть покрытие покупается красным гейтом.
Решение оставить абзацный уровень принято владельцем; обе дырки закрыты тестом, который
фиксирует их как известные, чтобы они не расширились молча.

`DOC_SUSPENSION_MARKERS` — только многословные маркеры. Омoним «раньше» в него не входит:
в `docs/06_operations_and_risks.md` «не удалять узлы **раньше** связей» — это порядок, а не
«раньше = снято», и такая строка прошла бы мимо проверки как история.
"""

from __future__ import annotations

import re

#: Снятые сущности схемы: как их называют. Это и есть тот самый один список.
#: Регистрозависимо: `Source` без границ слова ловит обычное «sources». Границы слова не
#: спасают от оператора `CONTAINS` языка Cypher — он встречается как отдельное слово
#: (`WHERE n.name CONTAINS 'x'`), и ловится; в эталоне набора это не мешает, потому что
#: текст факта про Cypher не встречается, а в документе такой случай надо смотреть глазами.
#:
#: `\bcypher_template\b` и `\bSource\b` не задевают `SourceProvider` / `SourceRef`: между
#: `Source` и `Provider` нет границы слова, поэтому такое имя ловится как другое слово.
SYMBOL_PATTERNS: dict[str, tuple[str, ...]] = {
    "edge CONTAINS": (r"\bCONTAINS\b",),
    "node Source": (r"\bSource\b",),
    "profile key cypher_template": (r"\bcypher_template\b",),
}

#: Контекстные правила потребителя эталона. Нужны только там, где символ встречается
#: законно: в домене `cinema` есть документ, буквально названный «Source», и вопрос
#: `cin_010` спрашивает, чем он отличается от источника документа, — это заголовок, а не
#: снятая нода. Снятая нода в эталоне всегда упоминается рядом с `Chunk` или со словом
#: «anchor». Для документа правило другое (см. `doc_claim_violations`), поэтому символ без
#: контекстного правила проверяется как есть.
DATASET_CONTEXT_RULES: dict[str, tuple[str, ...]] = {
    "node Source": (
        r"\bSource\b(?=[^|]{0,60}(?:Chunk|anchor))",
        r"(?:Chunk|anchor)(?=[^|]{0,60}\bSource\b)",
    ),
}

#: Имена снятых сущностей, в форме, которую читает гейт приёмки набора.
SUSPENDED_SYMBOLS: dict[str, tuple[str, ...]] = {
    name: DATASET_CONTEXT_RULES.get(name, patterns)
    for name, patterns in SYMBOL_PATTERNS.items()
}

#: Что означает «в этом абзаце сказано, что сущность снята».
#: Однословные формулировки здесь опасны: «раньше» означает ещё и порядок,
#: «нет» — ещё и «свойства нет», а это вовсе не про снятие сущности.
DOC_SUSPENSION_MARKERS: tuple[str, ...] = (
    "ADR-046",
    "в схеме нет",
    "не существует",
    "нет нод",
    "снят",
    "снята",
    "снято",
    "раньше — по ребру",
)


def symbols_of(line: str) -> list[str]:
    """Имена снятых сущностей, упомянутых в строке, — по правилам потребителя эталонного
    гейта (с контекстом: `Source` считается только рядом с `Chunk` или «anchor»)."""
    return [
        name
        for name, patterns in SUSPENDED_SYMBOLS.items()
        if any(re.search(pattern, line) for pattern in patterns)
    ]


def symbols_named(line: str) -> list[str]:
    """Имена снятых сущностей, просто названные в строке, — без контекста.

    Для документа контекстного правила не нужно: там ложное срабатывание — это не документ
    с именем «Source», а абзац, который называет снятое как существующее. Зато появляется
    другая осторожность: `SourceProvider` и `SourceRef` — другие имена, и границы слова их
    не задевают.
    """
    return [
        name
        for name, patterns in SYMBOL_PATTERNS.items()
        if any(re.search(pattern, line) for pattern in patterns)
    ]


def marked_suspended(paragraph: str) -> bool:
    """Помечен ли абзац как рассказ о снятом."""
    return any(marker in paragraph for marker in DOC_SUSPENSION_MARKERS)


def doc_claim_violations(paragraph: str) -> list[str]:
    """Снятые сущности, которые абзац называет, не сказав, что они сняты.

    Параграф — блок строк, отделённых пустой строкой. Возвращает имена, а не строки:
    отчёт нужен читателю, а вердикт выносит человек.
    """
    if marked_suspended(paragraph):
        return []
    return symbols_named(paragraph)


def paragraphs_of(text: str) -> list[tuple[int, str]]:
    """Абзацы как `(номер первой строки, текст)`. Нумерация — для отчёта, чтобы
    сопоставить находку с местом."""
    blocks: list[tuple[int, str]] = []
    current: list[str] = []
    start = 0
    for number, line in enumerate(text.replace("\r\n", "\n").split("\n"), 1):
        if line.strip():
            if not current:
                start = number
            current.append(line)
            continue
        if current:
            blocks.append((start, "\n".join(current)))
            current = []
    if current:
        blocks.append((start, "\n".join(current)))
    return blocks